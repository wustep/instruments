"""Write apps/web/src/ui/gl/outlines.ts from the traced outlines (scripts/trace-outline.py).

  python3 scripts/make-outlines.py            # traces .cache/refs-3d/{cello,violin}-front.jpg
"""
import json
import subprocess
import sys

SRC = {'CELLO': ('cello-front.jpg', 'J.-B. Vuillaume cello, The Met (CC0)'), 'VIOLIN': ('violin-front.jpg', 'A. Stradivari "Francesca" violin, 1694, The Met (CC0)')}
out = ['''// Plate outlines and f-holes traced from front photographs of real instruments (museum photographs on a
// plain backdrop, kept in .cache/refs-3d/ for analysis only; sources in docs/3d-reference.md), by
// scripts/trace-outline.py: the outline's half-width at 481 stations along the body (u = 0 at the
// neck end, 1 at the tail; as a fraction of the body length, both sides averaged) and the bass-side
// f-hole as a polygon (u, z), z towards the bass side from the centre line, in the same units.
// Generated by scripts/make-outlines.py; regenerate rather than editing by hand.
export interface Outline {
  /** half-width / body length at u = i / (n - 1) */
  hw: number[];
  /** the bass-side f-hole, (u, z / body length) */
  fhole: [number, number][];
  /** the traced bouts (full widths / body length) */
  bouts: { upper: number; c: number; lower: number };
}
''']
for name, (f, who) in SRC.items():
    d = json.loads(subprocess.run([sys.executable, 'scripts/trace-outline.py', f'.cache/refs-3d/{f}'], capture_output=True, text=True, check=True).stdout)
    hw = [s[1] for s in d['halfWidth']]
    sm = hw[:]
    for i in range(1, len(hw) - 1):
        if abs(hw[i + 1] - hw[i - 1]) < 0.004:
            sm[i] = (hw[i - 1] + 2 * hw[i] + hw[i + 1]) / 4
    sm[0] = sm[-1] = 0.0
    fmt = lambda v: ('%.4f' % v).rstrip('0').rstrip('.') if v else '0'
    out.append(f"/** traced from {who} ({d['bodyPx']} px body) */")
    out.append(f'export const {name}: Outline = {{')
    out.append('  hw: [' + ', '.join(fmt(v) for v in sm) + '],')
    out.append('  fhole: [' + ', '.join(f'[{a:.4f}, {b:.4f}]' for a, b in d['fhole']) + '],')
    b = d['bouts']
    out.append(f"  bouts: {{ upper: {b['upper']}, c: {b['c']}, lower: {b['lower']} }},")
    out.append('};')
open('apps/web/src/ui/gl/outlines.ts', 'w').write('\n'.join(out) + '\n')
print('wrote apps/web/src/ui/gl/outlines.ts')
